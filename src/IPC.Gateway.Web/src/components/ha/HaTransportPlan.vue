<template>
  <section v-if="visible" class="ha-transport-plan">
    <h3>{{ l('组网地址与证书变更','Network and certificate changes') }}</h3>
    <a-alert v-if="snapshot?.restartRequired" type="warning" show-icon
      :message="l('组网变更已登记，等待三个成员重启。','Network changes are registered and waiting for all three members to restart.')"
      :description="l('请按同一计划重启 A、B 网关服务和 C 见证成员服务；A、B 内置仲裁随网关重启。全部成员使用新地址和证书后，执行连接预检，再开启双机热备。重启前仍保留原运行配置。','Restart the gateway services on A and B and the witness service on C using this plan. The embedded arbiters on A and B restart with their gateways. Once every member uses the new endpoints and certificates, run precheck and enable failover. The running configuration is retained until restart.')" />
    <a-alert v-else-if="snapshot?.phase==='Completed'" type="success" show-icon
      :message="l('三个成员已加载同一组网变更计划。','All three members have loaded the same network migration plan.')"
      :description="l('请重新执行连接预检，确认后启用双机热备并应用运行配置。','Run precheck again, then enable failover and apply the operating configuration.')" />
    <p v-else>{{ l('先关闭双机热备并保存草稿，再准备三个成员的地址和证书。准备阶段会在各节点本机生成所需证书，私钥保留在各节点。确认后写入待生效配置，需手动重启三个成员。','Disable failover and save the draft before preparing member endpoints and certificates. Certificates are generated locally on each node; private keys remain there. Confirmation writes the pending configuration. All three members must then be restarted manually.') }}</p>
    <a-alert v-if="error" type="error" show-icon :message="error" />
    <a-alert v-else-if="snapshot?.message" :type="snapshot.phase==='Partial'?'warning':'info'" show-icon :message="haLabel(snapshot.message)" />
    <p v-if="planActive"><b>{{ l('迁移计划','Migration plan') }}</b> {{ snapshot?.planId || prepareId }} · {{ phaseLabel }}</p>
    <a-checkbox v-if="!planActive" v-model:checked="rotateCertificates" :disabled="locked || busy">
      {{ l('重新生成成员和网关证书','Generate new member and gateway certificates') }}
    </a-checkbox>
    <p v-if="!planActive && rotateCertificates" class="ha-note">{{ l('准备后将展示各节点实际生成的证书指纹，确认前请核对。草稿中填写的旧证书引用会随迁移计划更新。','Preparation displays the certificate fingerprints generated by each node for your review. The migration plan replaces the previous certificate references in the draft.') }}</p>
    <div class="ha-toolbar">
      <a-button v-if="!planActive || snapshot?.phase==='Preparing'" type="primary" :loading="busy" :disabled="!canPrepare" @click="prepare">
        {{ snapshot?.phase==='Preparing' ? l('重试准备原计划','Retry preparing this plan') : l('准备组网变更','Prepare network changes') }}
      </a-button>
      <a-button v-if="snapshot?.phase==='Prepared' || snapshot?.phase==='Partial'" type="primary" :loading="busy" :disabled="locked || busy" @click="confirmOpen=true">
        {{ snapshot.phase==='Partial' ? l('重试写入原计划','Retry writing this plan') : l('确认组网变更','Confirm network changes') }}
      </a-button>
      <a-button v-if="snapshot?.phase==='Preparing' || snapshot?.phase==='Prepared'" :disabled="locked || busy" @click="cancel">
        {{ l('放弃待确认计划','Discard unconfirmed plan') }}
      </a-button>
      <a-button :loading="refreshing" :disabled="busy || refreshing" @click="refresh">{{ tx('刷新') }}</a-button>
    </div>
    <p v-if="!planActive && !canPrepare" class="ha-note">{{ prepareReason }}</p>
    <div v-if="snapshot?.members?.length" class="ha-transport-members">
      <div v-for="member in snapshot.members" :key="member.nodeId" class="ha-transport-member">
        <b>{{ tx('节点') }} {{ member.nodeId }} · {{ memberStateLabel(member.state) }}</b>
        <dl class="ha-fields">
          <dt>{{ tx('仲裁客户端地址') }}</dt><dd>{{ member.clientUrl }}</dd>
          <dt>{{ tx('成员通信地址') }}</dt><dd>{{ member.peerUrl }}</dd>
          <template v-if="member.nodeId!=='C'"><dt>{{ tx('网关管理地址') }}</dt><dd>{{ member.gatewayUrl || '—' }}</dd></template>
          <dt>{{ l('成员证书指纹','Member certificate fingerprint') }}</dt><dd><code>{{ member.certificateRef }}</code></dd>
          <template v-if="member.gatewayCertificateSha256"><dt>{{ l('网关证书指纹','Gateway certificate fingerprint') }}</dt><dd><code>{{ member.gatewayCertificateSha256 }}</code></dd></template>
        </dl>
      </div>
    </div>
    <a-modal v-model:open="confirmOpen" centered :title="l('确认组网变更','Confirm network changes')" :ok-text="tx('确认')" :cancel-text="tx('取消')" :confirm-loading="busy" @ok="apply">
      <p>{{ l('将同一份变更计划写入 A、B、C。现有集群 ID、节点角色及持久仲裁记录保持不变。','The same migration plan will be written to A, B and C. The cluster ID, member roles and persistent arbiter records are retained.') }}</p>
      <p>{{ l('保存成功表示等待重启；不表示新地址和证书已经在运行。请完成三个成员的手动重启，再重新预检和启用热备。','A successful save means that restart is pending. New endpoints and certificates become active after all three members restart. Then rerun precheck and enable failover.') }}</p>
      <code>{{ snapshot?.planId }}</code>
    </a-modal>
  </section>
</template>
<script setup lang="ts">
import { computed, onBeforeUnmount, onMounted, ref, watch } from 'vue'
import { locale, tx } from '../../i18n'
import { haGet, haSend, haLabel, newHaId, type HaClusterSwitch, type HaConfig, type HaStatus } from '../../haApi'
interface TransportState {
  phase:'None'|'Preparing'|'Prepared'|'Partial'|'PendingRestart'|'Completed'
  planId?:string
  message?:string
  restartRequired:boolean
  rotateCertificates?:boolean
  members:{nodeId:string;clientUrl:string;peerUrl:string;gatewayUrl?:string;certificateRef:string;gatewayCertificateSha256?:string;state:string}[]
  config?:HaConfig
}
const props=defineProps<{draftVersion:number;dirty:boolean;saved:boolean;locked:boolean;scope:string;switchState?:HaClusterSwitch;status:HaStatus|null;transportChanged:boolean}>()
const emit=defineEmits<{lock:[locked:boolean];changed:[]}>()
function l(zh:string,en:string){return locale.value==='zh-CN'?zh:en}
const controller=new AbortController()
const snapshot=ref<TransportState>(),error=ref(''),busy=ref(false),refreshing=ref(false),confirmOpen=ref(false)
const storeKey='ipc.ha.transport-operation.'+props.scope
const rotateCertificates=ref(sessionStorage.getItem(storeKey+'.rotate')!=='false')
const prepareId=ref(sessionStorage.getItem(storeKey)||'')
const planActive=computed(()=>!!snapshot.value && !['None','Completed'].includes(snapshot.value.phase))
const visible=computed(()=>props.switchState?.phase==='Disabled' || props.transportChanged || planActive.value)
const canPrepare=computed(()=>!!snapshot.value && !refreshing.value && !props.locked && !busy.value && props.saved && !props.dirty && props.switchState?.phase==='Disabled' &&
  props.switchState.standaloneNode===props.status?.connectedNode && (!planActive.value || snapshot.value?.phase==='Preparing'))
const prepareReason=computed(()=>props.switchState?.phase!=='Disabled' ? l('请先关闭双机热备。','Disable failover first.') :
  props.switchState.standaloneNode!==props.status?.connectedNode ? l('请直连保留单机业务的网关准备组网变更。','Connect directly to the gateway reserved for standalone operation to prepare network changes.') :
  props.dirty || !props.saved ? l('请先保存当前草稿。','Save the current draft first.') : l('当前状态不允许准备组网变更。','Network changes cannot be prepared in the current state.'))
const phaseLabel=computed(()=>({None:l('未准备','Not prepared'),Preparing:l('正在准备','Preparing'),Prepared:l('已准备，等待确认','Prepared; awaiting confirmation'),
  Partial:l('部分成员已写入，请重试原计划','Partially written; retry this plan'),PendingRestart:l('等待重启','Restart pending'),Completed:l('已完成','Completed')})[snapshot.value?.phase || 'None'])
function memberStateLabel(state:string){
  const labels:Record<string,string>={Preparing:l('正在准备','Preparing'),Prepared:l('已准备','Prepared'),Installed:l('已写入','Written'),
    Applied:l('已写入','Written'),PendingRestart:l('等待重启','Restart pending'),Restarted:l('已重启','Restarted'),Completed:l('已完成','Completed')}
  return labels[state] || haLabel(state)
}
watch([planActive,busy],()=>emit('lock',planActive.value || busy.value),{immediate:true})
async function load(){
  const result=await haGet<TransportState>('transport',controller.signal)
  if(controller.signal.aborted)return
  const previous=snapshot.value?.phase
  snapshot.value=result
  if(typeof result.rotateCertificates==='boolean')rotateCertificates.value=result.rotateCertificates
  if(result.planId){prepareId.value=result.planId;sessionStorage.setItem(storeKey,result.planId)}
  if(result.phase==='Completed' || result.phase==='None'){prepareId.value='';sessionStorage.removeItem(storeKey)}
  if(result.phase==='Completed' && previous && previous!=='Completed')emit('changed')
}
async function refresh(){
  if(refreshing.value)return
  refreshing.value=true;error.value=''
  try{await load()}catch(e){if(!controller.signal.aborted)error.value=e instanceof Error?e.message:String(e)}
  finally{refreshing.value=false}
}
async function prepare(){
  if(!canPrepare.value)return
  busy.value=true;error.value=''
  prepareId.value ||=newHaId()
  sessionStorage.setItem(storeKey,prepareId.value)
  sessionStorage.setItem(storeKey+'.rotate',String(rotateCertificates.value))
  try{
    snapshot.value=await haSend<TransportState>('transport/prepare',{draftVersion:props.draftVersion,operationId:prepareId.value,
      expectedGeneration:props.switchState!.generation,rotateCertificates:rotateCertificates.value},'POST',controller.signal)
  }catch(e){
    if(!controller.signal.aborted){error.value=e instanceof Error?e.message:String(e);await load().catch(()=>{})}
  }finally{busy.value=false}
}
async function apply(){
  if(!snapshot.value?.planId || props.locked || busy.value)return
  busy.value=true;error.value='';confirmOpen.value=false
  try{snapshot.value=await haSend<TransportState>('transport/apply',{planId:snapshot.value.planId},'POST',controller.signal);emit('changed')}
  catch(e){if(!controller.signal.aborted){error.value=e instanceof Error?e.message:String(e);await load().catch(()=>{})}}
  finally{busy.value=false}
}
async function cancel(){
  if(!snapshot.value?.planId || props.locked || busy.value)return
  busy.value=true;error.value=''
  try{
    snapshot.value=await haSend<TransportState>('transport/cancel',{planId:snapshot.value.planId},'POST',controller.signal)
    prepareId.value='';sessionStorage.removeItem(storeKey);emit('changed')
  }catch(e){if(!controller.signal.aborted){error.value=e instanceof Error?e.message:String(e);await load().catch(()=>{})}}
  finally{busy.value=false}
}
let timer:number|undefined
onMounted(()=>{void refresh();timer=window.setInterval(()=>{if(!document.hidden && planActive.value && !busy.value && !refreshing.value)void refresh()},5000)})
onBeforeUnmount(()=>{controller.abort();window.clearInterval(timer);emit('lock',false)})
</script>
