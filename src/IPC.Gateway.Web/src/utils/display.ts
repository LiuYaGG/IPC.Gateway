export function permissionPageLabel(key: string, fallback = "其他权限") {
  const module = key.split(".")[0].toLowerCase();
  const page = module === "groups" || module === "tags" ? "devices" : module;
  return (
    pages[page] ?? (/[\u3400-\u9fff]/.test(fallback) ? fallback : "其他权限")
  );
}
export function permissionLabel(key: string, fallback?: string) {
  const normalized = key.toLowerCase();
  if (permissionOverrides[normalized]) return permissionOverrides[normalized];
  const parts = normalized.split(".");
  const page = pages[parts[0]];
  const action = actions[parts.at(-1) ?? ""];
  if (page && action) return `${action}${page}`;
  return fallback && /[\u3400-\u9fff]/.test(fallback) ? fallback : "其他权限";
}
